#!/usr/bin/env python3
"""Sample the blurred backdrops of luci-theme-omarchy from Omarchy's wallpapers.

    tools/sample-backdrops.py <omarchy-checkout>

Needs Pillow. For every palette it reads one wallpaper of the theme, the first
one unless PREFERRED names another, shrinks it to a grid of average colours and
writes the grids to backdrops.toml, along with the names of all the wallpapers
of the theme for the wallpaper buttons in the panel. No image is shipped:
tools/gen-palettes.py turns these colours into a soft gradient, and a palette
without a grid gets one made from its own colours.
"""
import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PALETTES = ROOT / 'palettes'
OUTPUT = ROOT / 'backdrops.toml'
COLUMNS, ROWS = 8, 5
# Where the first wallpaper of a theme makes a poor backdrop for its colours.
PREFERRED = {'tokyo-night': '6-oma-cityscape.jpg'}
# Links to, and stubs of, the Omarchy logo are not wallpapers to offer.
SMALLEST = 8 * 1024


def sample(path):
    """The picture as ROWS strings of COLUMNS space-separated hex colours."""
    with Image.open(path) as image:
        small = image.convert('RGB').resize((COLUMNS, ROWS), Image.Resampling.BOX)
    data = small.tobytes().hex()
    cell = 6
    return [' '.join(data[(y * COLUMNS + x) * cell:(y * COLUMNS + x + 1) * cell] for x in range(COLUMNS)) for y in range(ROWS)]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('omarchy', type=Path, help='directory that holds themes/<palette>/backgrounds/')
    args = ap.parse_args()

    lines = [
        '# Generated by tools/sample-backdrops.py. Do not edit.',
        '#',
        '# Average colours of one wallpaper of each Omarchy theme, as a grid of',
        f'# {COLUMNS} by {ROWS} cells. tools/gen-palettes.py turns them into the backdrop.',
    ]
    for palette in sorted(f.stem for f in PALETTES.glob('*.toml')):
        wallpapers = sorted((args.omarchy / 'themes' / palette / 'backgrounds').glob('*'))
        wallpapers = [w for w in wallpapers if w.is_file() and not w.is_symlink() and w.stat().st_size >= SMALLEST]
        if not wallpapers:
            print(f'{palette}: no wallpaper, skipped')
            continue
        chosen = next((w for w in wallpapers if w.name == PREFERRED.get(palette)), wallpapers[0])
        names = ', '.join(f'"{w.name}"' for w in wallpapers)
        lines += ['', f'[{palette}]', f'source = "{chosen.name}"', f'walls = [{names}]', 'rows = [']
        lines += [f'\t"{row}",' for row in sample(chosen)]
        lines += [']']
    OUTPUT.write_text('\n'.join(lines) + '\n')
    print(f'wrote {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
